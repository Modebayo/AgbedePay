// middleware/uploadAvatar.js — the ONLY way a file enters this application.
//
// WHY THIS FILE IS SO DEFENSIVE
//
// An avatar upload is an unauthenticated-writer, arbitrary-bytes feature. Before
// requireAuth there is nothing stopping a stranger from POSTing a file; and the
// single most common way image uploads get exploited is by trusting what the
// client SAYS the file is. So the rules here are:
//
//   1. The browser-supplied Content-Type and filename are treated as UNTRUSTED
//      INPUT, not as facts. `req.file.mimetype` is whatever the attacker typed.
//      The real type is sniffed from the first bytes of the file (sniffMime).
//   2. The stored filename is generated by us from crypto.randomUUID(). The
//      client's filename is NEVER used for the path — that is what stops
//      "../../../etc/passwd" and "avatar.php" from ever reaching the disk.
//   3. Size is capped in TWO places: multer's own limit (so a huge body is
//      refused while streaming, before it is buffered) and again after sniffing.
//   4. The extension is derived from the sniffed bytes, not from the client, so
//      a PHP or SVG payload can never land on disk with a matching extension.
//   5. Files are written OUTSIDE frontend/. express.static serves frontend/ with
//      no auth, so an upload there would be world-readable to anyone with the
//      filename. These are served by an authenticated route instead.
//
// Why these formats: JPEG, PNG and WebP cover effectively every phone camera and
// browser upload, and all three can be identified unambiguously from a fixed
// byte prefix. SVG is deliberately EXCLUDED — it is a script-bearing document
// format, and serving one from the app's own origin would be a stored-XSS hole
// (img-src in the CSP would not save you, because a direct navigation to the
// file executes the script). GIF is excluded for the same class of reason: it can
// carry script in older engines.

import crypto from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import fs from "node:fs/promises";
import { ApiError } from "../utils/errors.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// OUTSIDE frontend/ on purpose — see point 5 above.
export const AVATAR_DIR = path.resolve(__dirname, "../../storage/avatars");

// 2 MB. A profile picture is displayed at 38px in the topbar and at most ~160px
// on the profile page; anything much larger is a phone photo the browser failed
// to downscale, and storing it would be pure waste. The frontend also downscales
// before upload, so in practice files arrive far below this.
export const MAX_AVATAR_BYTES = 2 * 1024 * 1024;

const ALLOWED = new Set(["image/jpeg", "image/png", "image/webp"]);

// The canonical extension for each sniffed type. Keyed by SNIFFED mime, never by
// the client's claimed type, so a file can only ever be stored under an extension
// that matches what it actually is.
const EXTENSION = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
};

/**
 * Identifies an image from its first bytes.
 *
 * This is the security-critical function in the feature. It reads a fixed-length
 * prefix and matches known signatures, and returns null for anything
 * unrecognised — an allowlist, so a novel format is rejected by default rather
 * than admitted by accident.
 *
 * @param {Buffer} buf at least the first 12 bytes of the file
 * @returns {string|null} a MIME type, or null if it is not a permitted image
 */
export function sniffMime(buf) {
  if (!Buffer.isBuffer(buf) || buf.length < 12) return null;

  // JPEG: FF D8 FF, then a marker byte. The fourth byte distinguishes a real
  // JFIF/Exif stream from other FF D8 FF prefixed data.
  if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) {
    const marker = buf[3];
    if (marker === 0xe0 || marker === 0xe1 || marker === 0xdb || marker === 0xee) {
      return "image/jpeg";
    }
    return null;
  }

  // PNG: the full 8-byte signature, not just the first four. "8950 4E47" alone
  // is short enough to collide by accident.
  if (
    buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4e && buf[3] === 0x47 &&
    buf[4] === 0x0d && buf[5] === 0x0a && buf[6] === 0x1a && buf[7] === 0x0a
  ) {
    return "image/png";
  }

  // WebP: "RIFF" .... "WEBP" — a container format, so the magic number is the
  // brand at offset 8, not the first four bytes.
  if (
    buf.toString("ascii", 0, 4) === "RIFF" &&
    buf.toString("ascii", 8, 12) === "WEBP"
  ) {
    return "image/webp";
  }

  return null;
}

// multer is loaded LAZILY, on first use, and never with a top-level `import`.
//
// This is deliberate and it was a real production incident: this module sits in
// the startup import chain (app.js → routes/userRouter.js → controllers/
// userController.js → this file). With a static `import multer from "multer"`,
// a deployment whose node_modules was missing that one package threw
// ERR_MODULE_NOT_FOUND while the module graph was still loading — before
// app.listen() ever ran. The process died, nothing bound the port, and the
// reverse proxy returned 502 for EVERY route including /health. A profile
// picture feature took the whole site offline.
//
// Deferring the load means a missing or broken multer can now only ever break
// the one endpoint that needs it. Every other route — login, transfers,
// everything — keeps serving, and this one returns a clear 501 telling the
// operator what to install.
let multerSingleton = null;

function getMulter() {
  if (multerSingleton) return multerSingleton;
  try {
    // createRequire resolves CommonJS packages from an ES module. multer is CJS.
    const require = createRequire(import.meta.url);
    multerSingleton = require("multer");
    return multerSingleton;
  } catch (err) {
    throw new ApiError(
      501,
      "Profile picture uploads are unavailable: the 'multer' package is not installed. Run `npm install` on the server.",
      "UPLOAD_DEPENDENCY_MISSING"
    );
  }
}

/**
 * Builds the multer middleware: accepts exactly one file field, buffers it in
 * memory, validates the bytes, and writes it to a generated filename.
 *
 * In-memory (`memoryStorage`) rather than disk: the file is only written after
 * the bytes have been sniffed, so a rejected upload never touches the disk at
 * all. At a 2 MB cap that is a safe amount of memory to hold briefly.
 *
 * Errors are thrown as ApiError so the central errorHandler formats them like
 * every other failure in the app — the client always gets
 * { success: false, message, code } and never a raw multer error.
 */
export function avatarUpload(req, res, next) {
  const multer = getMulter();
  return multer({
    storage: multer.memoryStorage(),
    limits: {
      fileSize: MAX_AVATAR_BYTES,
      files: 1, // one image, never a bundle
      fields: 0, // no text fields expected; the picture is the whole request
    },
    fileFilter(_req, file, cb) {
      // A first cheap gate on the DECLARED type, purely to reject obvious junk
      // early. This is NOT the security check — fileFilter cannot see the bytes,
      // and `file.mimetype` is attacker-controlled. The real check is sniffMime
      // below, which runs on the actual buffer.
      if (file.mimetype && !ALLOWED.has(file.mimetype)) {
        cb(
          new ApiError(
            415,
            "Profile pictures must be a JPEG, PNG or WebP image",
            "UNSUPPORTED_IMAGE_TYPE"
          )
        );
        return;
      }
      cb(null, true);
    },
  }).single("avatar")(req, res, next);
}

/**
 * Runs after multer. Sniffs the real bytes and persists the file.
 *
 * Separated from the multer middleware on purpose: multer's job is parsing, and
 * this file's job is deciding whether the result is safe to keep. Keeping them
 * apart means the security decision is testable on its own, without a request.
 *
 * @returns {Promise<{filename: string, mime: string, sizeBytes: number}>}
 */
export async function persistAvatar(file) {
  if (!file || !file.buffer) {
    throw new ApiError(400, "No image was uploaded", "NO_FILE");
  }
  if (file.size > MAX_AVATAR_BYTES) {
    throw new ApiError(413, `That image is too large. The limit is ${Math.floor(MAX_AVATAR_BYTES / 1024 / 1024)} MB.`, "IMAGE_TOO_LARGE");
  }

  const mime = sniffMime(file.buffer);
  if (!mime || !ALLOWED.has(mime)) {
    // The message names the problem without echoing back what was detected,
    // which would confirm to a prober which formats are in use.
    throw new ApiError(415, "That file is not a valid JPEG, PNG or WebP image", "UNSUPPORTED_IMAGE_TYPE");
  }

  // The name is OURS, built from a UUID. crypto.randomUUID is not
  // user-influenced, so the path can never traverse or collide.
  const filename = `${crypto.randomUUID()}.${EXTENSION[mime]}`;

  await fs.mkdir(AVATAR_DIR, { recursive: true });

  // `wx` fails if the path already exists rather than overwriting, so a
  // (astronomically unlikely) UUID collision cannot destroy another user's
  // picture.
  await fs.writeFile(path.join(AVATAR_DIR, filename), file.buffer, { flag: "wx" });

  return { filename, mime, sizeBytes: file.size };
}

/**
 * Deletes a stored avatar. Never throws — a failure to clean up an old file
 * must not fail the request that replaced it, or the user is left unable to
 * change their picture because of an unrelated disk problem.
 */
export async function deleteAvatar(filename) {
  if (!filename) return;
  // Defence in depth: even though every filename we write is a bare UUID, this
  // function will only ever unlink a plain filename inside AVATAR_DIR. A value
  // that somehow contains a separator or ".." is rejected outright rather than
  // resolved, so a tampered database row cannot be used to delete arbitrary
  // files on the server.
  if (typeof filename !== "string" || !/^[A-Za-z0-9._-]+$/.test(filename)) return;

  const full = path.join(AVATAR_DIR, filename);
  if (path.dirname(full) !== AVATAR_DIR) return;

  await fs.unlink(full).catch(() => {});
}

/**
 * Resolves a stored filename to an absolute path, or null if it is not a
 * readable avatar inside AVATAR_DIR. The same containment check as above.
 */
export function resolveAvatarPath(filename) {
  if (typeof filename !== "string" || !/^[A-Za-z0-9._-]+$/.test(filename)) return null;
  const full = path.join(AVATAR_DIR, filename);
  if (path.dirname(full) !== AVATAR_DIR) return null;
  return full;
}
